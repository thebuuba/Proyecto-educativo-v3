import {readFileSync} from 'node:fs'
import {resolve} from 'node:path'
import {describe,it,expect} from 'vitest'
import {recommend} from './recommendation-engine'
const bank=JSON.parse(readFileSync(resolve(process.cwd(),'../../data/evaluation-instruments/curricular-audit/len1-guia-v1.json'),'utf8'))
const formats=['rubrica','lista-cotejo','escala','lista-ponderada'] as const
const run=(index:number,format:typeof formats[number])=>recommend({activityTitle:bank.cases[index].title,description:bank.cases[index].description,maxScore:17.35,participationMode:index===4?'GROUP':'INDIVIDUAL',preferredInstrumentType:format},bank.context,null,[],'UNMAPPED',null)
const text=(p:ReturnType<typeof run>)=>p.criteria.map(c=>c.description).join(' ')
describe('Guía turística1: acciones y requisitos curriculares del banco previo',()=>{
 for(const format of formats){
  it(`${format}: Hagan una guía reconoce el producto sin requisitos materiales inventados`,()=>{
   const p=run(0,format)
   expect(p.activityType).toBe('TOURIST_GUIDE_CREATION')
   expect(text(p)).toMatch(/barrio/)
   expect(text(p)).toMatch(/visitante|no conoce/)
   expect(text(p)).not.toMatch(/mapa|fotografía|borrador|publica|portada|presente.*indicativo/)
   expect(p.criteria.every(c=>!c.templateId.startsWith('language-'))).toBe(true)
  })
  it(`${format}: selección y clasificación responden a información disponible y familias`,()=>{
   const p=run(1,format),t=text(p)
   expect(t).toMatch(/clasifi|categorías/)
   expect(t).toMatch(/función/)
   expect(t).toMatch(/información.*disponible|información.*reunida/)
   expect(t).toMatch(/familias/)
   expect(t).toMatch(/portada.*información.*cierre/)
   expect(t).toMatch(/espaciales.*temporales|espacio.*tiempo/)
   expect(t).toMatch(/ubicación|topográfica/)
  })
  it(`${format}: respeta mapa o collage y no duplica el mismo requisito visual`,()=>{
   const p=run(1,format),visual=p.criteria.filter(c=>/mapa|collage|recurso visual/.test(JSON.stringify(c)))
   expect(visual).toHaveLength(1)
   expect(visual[0].description).toMatch(/mapa o collage/)
   expect(text(p)).not.toMatch(/mapa y collage|excursión|cooperación estructurada/)
  })
  it(`${format}: borrador, final y publicación no desaparecen`,()=>{
   const p=run(1,format),t=text(p)
   expect(t).toMatch(/borrador.*versión final/)
   expect(t).toMatch(/mural/)
   const revision=p.criteria.find(c=>c.templateId==='guide-process-revision')!
   expect(revision).toBeDefined()
   if(format==='rubrica'||format==='escala')expect(revision.descriptors[0].text).toMatch(/ambas versiones|borrador.*final/)
  })
  it(`${format}: lectura no se transforma en creación por No diseñen otra guía`,()=>{
   const p=run(2,format),t=text(p)
   expect(p.activityType).toBe('TOURIST_GUIDE_ANALYSIS')
   expect(t).toMatch(/destinatario|quién/)
   expect(t).toMatch(/portada.*información.*cierre/)
   expect(t).toMatch(/apariencia.*estímulos.*atractivos.*contenido/)
   expect(t).toMatch(/mapa.*lugares/)
   expect(t).toMatch(/vocabulario.*persuasivo|palabras.*invitan/)
   expect(t).toMatch(/evidencias|ejemplos|datos/)
   expect(t).not.toMatch(/Organiza la guía con|Emplea.*en el texto|escritura|Publica|Incorpora/)
  })
  it(`${format}: revisión conserva datos y evalúa grados y clases de adjetivos`,()=>{
   const p=run(3,format),t=text(p)
   expect(t).toMatch(/Corrige|Revisa/)
   expect(t).toMatch(/lugares.*datos|datos.*lugares/)
   expect(t).toMatch(/sustantivos propios.*comunes.*abstractos/)
   expect(t).toMatch(/calificativos.*determinativos/)
   expect(t).toMatch(/grados/)
   expect(t).toMatch(/presente.*indicativo/)
   expect(t).not.toMatch(/acciones terminadas|borrador|contenido, organización/)
  })
  it(`${format}: revisión explica núcleo/modificadores y puntuación sin otra guía`,()=>{
   const p=run(3,format),t=text(p)
   expect(t).toMatch(/núcleo.*modificador directo.*indirecto|núcleo.*modificadores directo e indirecto/)
   expect(t).toMatch(/explica.*ejemplos/)
   expect(t).toMatch(/comas.*dos puntos.*comillas.*interrogación.*exclamación/)
   expect(t).toMatch(/original.*corrección/)
   expect(t).not.toMatch(/mapa|recorrido.*nuevo|Organiza la guía/)
  })
  it(`${format}: la presentación usa recursos lingüísticos, no exige analizarlos`,()=>{
   const p=run(4,format),t=text(p)
   expect(p.activityType).toBe('TOURIST_GUIDE_PRESENTATION')
   expect(t).toMatch(/fichas/)
   expect(t).toMatch(/clasifi|categorías/)
   expect(t).toMatch(/propios.*comunes/)
   expect(t).toMatch(/adjetivos/)
   expect(t).toMatch(/topográfica|ubicación/)
   expect(t).toMatch(/espaciales.*temporales/)
   expect(t).toMatch(/mapa.*dado/)
   expect(t).toMatch(/cada integrante|aportación individual/i)
   expect(JSON.stringify(p.criteria)).not.toMatch(/Identifica.*sustantivos|Identifica.*adjetivos|Identifica.*conectores|No incorpora[^".]*en su texto/)
  })
  it(`${format}: escucha conserva anticipación, contraste, paráfrasis y clasificación`,()=>{
   const p=run(5,format),t=text(p)
   expect(p.activityType).toBe('TOURIST_GUIDE_ANALYSIS')
   expect(t).toMatch(/predicción|anticipación/)
   expect(t).toMatch(/título.*mapa/)
   expect(t).toMatch(/comprueba|contrasta/)
   expect(t).toMatch(/escuchad|audio/)
   expect(t).toMatch(/sus palabras|propias palabras/)
   expect(t).toMatch(/clasifi|categorías/)
   expect(t).toMatch(/cualidades.*adjetivos|adjetivos.*cualidades/)
   expect(t).not.toMatch(/texto leído|Identifica los adjetivos|escritura|Organiza la guía|guía nueva/)
   expect(p.totalScoreUnits).toBe(1735)
   expect(p.criteria.length).toBeLessThanOrEqual(20)
  })
 }
})
